"""Step 5: write js/data-version.js with a short hash of everything under data/, so data URLs change
(and browsers re-download) only when the data does."""
import hashlib
import os

from common import DATA, ROOT

h = hashlib.sha256()
for dirpath, dirnames, filenames in sorted(os.walk(DATA)):
    dirnames.sort()
    for f in sorted(filenames):
        p = os.path.join(dirpath, f)
        h.update(os.path.relpath(p, DATA).encode())
        with open(p, 'rb') as fh:
            h.update(fh.read())
v = h.hexdigest()[:10]
with open(os.path.join(ROOT, 'js', 'data-version.js'), 'w') as f:
    f.write(f"// Generated by tools/build_version.py. Changes whenever anything in data/ changes.\nexport const DATA_VERSION = '{v}';\n")
print('data version', v)
